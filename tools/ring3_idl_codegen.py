#!/usr/bin/env python3
"""Deterministic, strict Ring3 control-plane IDL compiler.

Generates only no_std field descriptors consumed by the *staged* Ring3
codec. Does not change the live RustOS syscall or IPC ABI. Inputs are
untrusted until this script validates every field and range.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "schemas/ring3/control.json"
OUTPUT = ROOT / "libs/rustos-component-model/src/generated_idl.rs"
MAX_BODY = 64 * 1024
MAX_FIELDS = 64
MAX_INTERFACES = 64
TYPES = {
    "bool": ("Bool", 1),
    "u16": ("U16", 2),
    "u32": ("U32", 4),
    "u64": ("U64", 8),
    "utf8": ("Utf8", None),
    "bytes": ("Bytes", None),
}
IDENT = re.compile(r"^[a-z][a-z0-9_]*$")


def mapping(value, allowed, required, where):
    if not isinstance(value, dict):
        raise ValueError(f"{where}: expected object")
    extra = set(value) - set(allowed)
    absent = set(required) - set(value)
    if extra or absent:
        raise ValueError(f"{where}: unknown={sorted(extra)} missing={sorted(absent)}")
    return value


def integer(value, minimum, maximum, where):
    # bool is a subclass of int in Python; disallow it explicitly.
    if type(value) is not int or not minimum <= value <= maximum:
        raise ValueError(f"{where}: expected integer in [{minimum}, {maximum}]")
    return value


def identifier(value, where):
    if not isinstance(value, str) or not IDENT.fullmatch(value):
        raise ValueError(f"{where}: noncanonical snake_case identifier")
    return value


def parse(path):
    with path.open("r", encoding="utf-8") as fd:
        document = json.load(fd)
    mapping(document, {"version", "interfaces"}, {"version", "interfaces"}, "root")
    if document["version"] != 1 or type(document["version"]) is not int:
        raise ValueError("root: expected schema version 1")
    interfaces = document["interfaces"]
    if not isinstance(interfaces, list) or not 1 <= len(interfaces) <= MAX_INTERFACES:
        raise ValueError("root: invalid interface count")
    used_names, used_opcodes = set(), set()
    checked = []
    for index, iface in enumerate(interfaces):
        where = f"interface[{index}]"
        mapping(iface, {"name", "opcode", "fields"}, {"name", "opcode", "fields"}, where)
        name = identifier(iface["name"], where + ".name")
        opcode = integer(iface["opcode"], 1, 65535, where + ".opcode")
        if name in used_names or opcode in used_opcodes:
            raise ValueError(where + ": duplicate interface name or opcode")
        used_names.add(name)
        used_opcodes.add(opcode)
        fields = iface["fields"]
        if not isinstance(fields, list) or not 1 <= len(fields) <= MAX_FIELDS:
            raise ValueError(where + ": invalid field count")
        used_field_names, last_tag = set(), 0
        entries = []
        for j, field in enumerate(fields):
            place = f"{where}.fields[{j}]"
            mapping(field, {"name", "tag", "type", "required", "max_len"},
                    {"name", "tag", "type", "required"}, place)
            field_name = identifier(field["name"], place + ".name")
            tag = integer(field["tag"], 1, 65535, place + ".tag")
            if tag <= last_tag or field_name in used_field_names:
                raise ValueError(place + ": duplicate, unordered or reused field")
            used_field_names.add(field_name)
            last_tag = tag
            kind = field["type"]
            if not isinstance(kind, str) or kind not in TYPES:
                raise ValueError(place + ": unknown field kind")
            if type(field["required"]) is not bool:
                raise ValueError(place + ": required must be boolean")
            rust_kind, fixed = TYPES[kind]
            if fixed is not None:
                if "max_len" in field and field["max_len"] != fixed:
                    raise ValueError(place + ": fixed field width mismatch")
                max_len = fixed
            else:
                if "max_len" not in field:
                    raise ValueError(place + ": dynamic fields require max_len")
                max_len = integer(field["max_len"], 1, min(65535, MAX_BODY), place + ".max_len")
            entries.append((tag, rust_kind, field["required"], max_len))
        checked.append((name.upper(), opcode, entries))
    return checked


def render(specs):
    lines = [
        "// @generated by tools/ring3_idl_codegen.py; DO NOT EDIT.",
        "// Staged control plane only: live service wire ABI is unchanged.",
        "use crate::idl::{FieldKind, FieldSpec, Schema};",
        "",
    ]
    for name, opcode, fields in specs:
        lines.append(f"pub const {name}_FIELDS: [FieldSpec; {len(fields)}] = [")
        for tag, kind, required, size in fields:
            flag = "true" if required else "false"
            lines.append("    FieldSpec {"
                         f" tag: {tag}, kind: FieldKind::{kind},"
                         f" required: {flag}, max_len: {size} "
                         "},")
        lines.append("];")
        lines.append(f"pub const {name}: Schema<'static> = Schema {{")
        lines.append(f"    opcode: {opcode},")
        lines.append(f"    fields: &{name}_FIELDS,")
        lines.append("};")
        lines.append("")
    lines.extend([
        "#[cfg(test)]",
        "mod tests {",
        "    use super::*;",
        "    use crate::idl::{Builder, Message};",
        "    #[test]",
        "    fn all_generated_schemas_validate() {",
        "        for schema in [",
    ])
    for name, _, _ in specs:
        lines.append(f"            {name},")
    lines.extend([
        "        ] {",
        "            assert!(schema.validate().is_ok());",
        "        }",
        "    }",
        "    #[test]",
        "    fn canonical_component_command_roundtrips() {",
        "        let mut builder = Builder::new(COMPONENT_COMMAND).unwrap();",
        "        builder.field(1, &5u64.to_le_bytes()).unwrap();",
        "        builder.field(2, &1u16.to_le_bytes()).unwrap();",
        "        builder.field(3, &8u64.to_le_bytes()).unwrap();",
        "        let bytes = builder.finish(99).unwrap();",
        "        let message = Message::decode(COMPONENT_COMMAND, &bytes).unwrap();",
        "        assert_eq!(message.header().request_id, 99);",
        "        assert_eq!(message.field(1).unwrap().as_u64(), Ok(5));",
        "        assert_eq!(message.field(2).unwrap().as_u16(), Ok(1));",
        "    }",
        "}",
        "",
    ])
    raw = "\n".join(lines)
    result = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=raw, text=True, encoding="utf-8", capture_output=True, check=True,
    )
    return result.stdout


def main():
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true")
    group.add_argument("--write", action="store_true")
    args = parser.parse_args()
    try:
        result = render(parse(INPUT))
    except (ValueError, OSError, json.JSONDecodeError, subprocess.CalledProcessError) as error:
        print(f"Ring3 IDL generation failed: {error}", file=sys.stderr)
        return 2
    if args.check:
        try:
            existing = OUTPUT.read_text(encoding="utf-8")
        except FileNotFoundError:
            existing = ""
        if existing != result:
            print(f"Generated IDL drift: run python3 {Path(__file__).name} --write", file=sys.stderr)
            return 1
        print("Ring3 IDL generated descriptors are current")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(result, encoding="utf-8")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
