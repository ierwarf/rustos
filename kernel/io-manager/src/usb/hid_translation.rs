pub(super) fn hid_modifier_mask(usage: u8) -> Option<u8> {
    match usage {
        0xE0 => Some(1 << 0),
        0xE1 => Some(1 << 1),
        0xE2 => Some(1 << 2),
        0xE3 => Some(1 << 3),
        0xE4 => Some(1 << 4),
        0xE5 => Some(1 << 5),
        0xE6 => Some(1 << 6),
        0xE7 => Some(1 << 7),
        _ => None,
    }
}

pub(super) fn mouse_buttons(buttons: u8) -> u8 {
    let mut value = 0u8;
    if buttons & POINTER_BUTTON_LEFT != 0 {
        value |= 1 << 0;
    }
    if buttons & POINTER_BUTTON_RIGHT != 0 {
        value |= 1 << 1;
    }
    if buttons & POINTER_BUTTON_MIDDLE != 0 {
        value |= 1 << 2;
    }
    value
}

pub(super) fn pointer_buttons_from_report(buttons: u8) -> u8 {
    let mut value = 0u8;
    if buttons & (1 << 0) != 0 {
        value |= POINTER_BUTTON_LEFT;
    }
    if buttons & (1 << 1) != 0 {
        value |= POINTER_BUTTON_RIGHT;
    }
    if buttons & (1 << 2) != 0 {
        value |= POINTER_BUTTON_MIDDLE;
    }
    value
}

pub(super) fn clamp_i8(value: i32) -> i8 {
    value.clamp(i8::MIN as i32, i8::MAX as i32) as i8
}

